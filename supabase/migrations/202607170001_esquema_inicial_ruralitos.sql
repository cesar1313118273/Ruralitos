create or replace function public.crear_organizacion_inicial(
  p_nombre text,
  p_codigo text,
  p_establecimiento_id bigint default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_organizacion uuid;
  v_codigo text := upper(btrim(p_codigo));
begin
  if v_usuario is null then
    raise exception 'Debes iniciar sesion.' using errcode = '42501';
  end if;

  if char_length(btrim(p_nombre)) not between 3 and 120 then
    raise exception 'El nombre debe tener entre 3 y 120 caracteres.' using errcode = '22023';
  end if;

  if v_codigo !~ '^[A-Z0-9_-]{3,30}$' then
    raise exception 'El codigo debe tener entre 3 y 30 letras, numeros, guiones o guion bajo.' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.miembros_organizacion
     where usuario_id = v_usuario and activo
  ) then
    raise exception 'El usuario ya pertenece a una organizacion activa.' using errcode = '23505';
  end if;

  if p_establecimiento_id is not null and not exists (
    select 1 from public.establecimientos_salud
     where id = p_establecimiento_id and activo
  ) then
    raise exception 'El establecimiento seleccionado no existe o esta inactivo.' using errcode = '23503';
  end if;

  insert into public.organizaciones (nombre, codigo, creado_por)
  values (btrim(p_nombre), v_codigo, v_usuario)
  returning id into v_organizacion;

  insert into public.miembros_organizacion (
    organizacion_id, usuario_id, establecimiento_id, rol, activo, creado_por
  ) values (
    v_organizacion, v_usuario, p_establecimiento_id, 'ADMIN', true, v_usuario
  );

  return v_organizacion;
end;
$$;

create or replace function public.crear_invitacion(
  p_organizacion_id uuid,
  p_correo text default null,
  p_rol text default 'MEDICO',
  p_establecimiento_id bigint default null,
  p_horas_vigencia integer default 168
)
returns table (codigo text, expira_en timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_codigo text;
  v_expira timestamptz;
  v_rol text := upper(btrim(p_rol));
begin
  if not public.es_admin(p_organizacion_id) then
    raise exception 'Solo un administrador puede invitar usuarios.' using errcode = '42501';
  end if;

  if v_rol not in ('ADMIN', 'MEDICO', 'ESTADISTICA') then
    raise exception 'Rol no valido.' using errcode = '22023';
  end if;

  if p_horas_vigencia not between 1 and 720 then
    raise exception 'La vigencia debe estar entre 1 y 720 horas.' using errcode = '22023';
  end if;

  if p_establecimiento_id is not null and not exists (
    select 1 from public.establecimientos_salud
     where id = p_establecimiento_id and activo
  ) then
    raise exception 'El establecimiento seleccionado no existe o esta inactivo.' using errcode = '23503';
  end if;

  v_codigo := upper(encode(extensions.gen_random_bytes(8), 'hex'));
  v_expira := now() + make_interval(hours => p_horas_vigencia);

  insert into public.invitaciones_organizacion (
    organizacion_id,
    correo,
    rol,
    establecimiento_id,
    codigo_hash,
    expira_en,
    creado_por
  ) values (
    p_organizacion_id,
    nullif(lower(btrim(p_correo)), ''),
    v_rol,
    p_establecimiento_id,
    extensions.digest(v_codigo, 'sha256'),
    v_expira,
    auth.uid()
  );

  return query select v_codigo, v_expira;
end;
$$;

create or replace function public.aceptar_invitacion(p_codigo text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_correo text;
  v_invitacion public.invitaciones_organizacion%rowtype;
begin
  if v_usuario is null then
    raise exception 'Debes iniciar sesion.' using errcode = '42501';
  end if;

  select lower(email) into v_correo
    from auth.users
   where id = v_usuario;

  select * into v_invitacion
    from public.invitaciones_organizacion
   where codigo_hash = extensions.digest(upper(btrim(p_codigo)), 'sha256')
     and usado_en is null
     and expira_en > now()
   for update;

  if not found then
    raise exception 'El codigo es invalido, ya fue usado o expiro.' using errcode = '22023';
  end if;

  if v_invitacion.correo is not null
     and lower(v_invitacion.correo) <> v_correo then
    raise exception 'La invitacion pertenece a otro correo.' using errcode = '42501';
  end if;

  insert into public.miembros_organizacion (
    organizacion_id, usuario_id, establecimiento_id, rol, activo, creado_por
  ) values (
    v_invitacion.organizacion_id,
    v_usuario,
    v_invitacion.establecimiento_id,
    v_invitacion.rol,
    true,
    v_invitacion.creado_por
  )
  on conflict (organizacion_id, usuario_id) do update
    set establecimiento_id = excluded.establecimiento_id,
        rol = excluded.rol,
        activo = true,
        updated_at = now();

  update public.invitaciones_organizacion
     set usado_en = now(), usado_por = v_usuario
   where id = v_invitacion.id;

  return v_invitacion.organizacion_id;
end;
$$;

revoke all on function public.crear_organizacion_inicial(text, text, bigint) from public;
revoke all on function public.crear_invitacion(uuid, text, text, bigint, integer) from public;
revoke all on function public.aceptar_invitacion(text) from public;
grant execute on function public.crear_organizacion_inicial(text, text, bigint) to authenticated;
grant execute on function public.crear_invitacion(uuid, text, text, bigint, integer) to authenticated;
grant execute on function public.aceptar_invitacion(text) to authenticated;

