create or replace function public.actualizar_marca_tiempo()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.actualizar_version_sync()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  new.version := old.version + 1;
  return new;
end;
$$;

create or replace function public.uuid_seguro(valor text)
returns uuid
language plpgsql
immutable
set search_path = ''
as $$
begin
  return valor::uuid;
exception when others then
  return null;
end;
$$;

revoke all on function public.actualizar_marca_tiempo() from public;
revoke all on function public.actualizar_version_sync() from public;
grant execute on function public.uuid_seguro(text) to authenticated;

