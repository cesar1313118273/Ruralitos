create policy adjuntos_storage_leer
on storage.objects for select to authenticated
using (
  bucket_id = 'fichas-adjuntos'
  and public.es_miembro(public.uuid_seguro((storage.foldername(name))[1]))
);

create policy adjuntos_storage_insertar
on storage.objects for insert to authenticated
with check (
  bucket_id = 'fichas-adjuntos'
  and public.puede_editar(public.uuid_seguro((storage.foldername(name))[1]))
);

create policy adjuntos_storage_actualizar
on storage.objects for update to authenticated
using (
  bucket_id = 'fichas-adjuntos'
  and public.puede_editar(public.uuid_seguro((storage.foldername(name))[1]))
)
with check (
  bucket_id = 'fichas-adjuntos'
  and public.puede_editar(public.uuid_seguro((storage.foldername(name))[1]))
);

create policy adjuntos_storage_eliminar
on storage.objects for delete to authenticated
using (
  bucket_id = 'fichas-adjuntos'
  and public.puede_editar(public.uuid_seguro((storage.foldername(name))[1]))
);

