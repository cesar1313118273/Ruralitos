-- El perfil se crea automaticamente al registrar una cuenta en Supabase Auth.
create or replace function public.crear_perfil_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfiles (id, cedula, nombres, cargo, correo, telefono)
  values (
    new.id,
    nullif(btrim(new.raw_user_meta_data ->> 'cedula'), ''),
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'nombres'), ''), ''),
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'cargo'), ''), ''),
    coalesce(new.email, ''),
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'telefono'), ''), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.sincronizar_correo_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.perfiles
     set correo = coalesce(new.email, '')
   where id = new.id;
  return new;
end;
$$;

revoke all on function public.crear_perfil_nuevo_usuario() from public;
revoke all on function public.sincronizar_correo_perfil() from public;

create trigger ruralitos_auth_usuario_creado
after insert on auth.users
for each row execute function public.crear_perfil_nuevo_usuario();

create trigger ruralitos_auth_correo_actualizado
after update of email on auth.users
for each row
when (old.email is distinct from new.email)
execute function public.sincronizar_correo_perfil();

-- Estas funciones evitan recursion en las politicas RLS de membresias.
create or replace function public.es_miembro(p_organizacion_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.miembros_organizacion m
     where m.organizacion_id = p_organizacion_id
       and m.usuario_id = (select auth.uid())
       and m.activo
  );
$$;

create or replace function public.es_admin(p_organizacion_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.miembros_organizacion m
     where m.organizacion_id = p_organizacion_id
       and m.usuario_id = (select auth.uid())
       and m.activo
       and m.rol = 'ADMIN'
  );
$$;

create or replace function public.puede_editar(p_organizacion_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.miembros_organizacion m
     where m.organizacion_id = p_organizacion_id
       and m.usuario_id = (select auth.uid())
       and m.activo
       and m.rol in ('ADMIN', 'MEDICO')
  );
$$;

create or replace function public.comparte_organizacion(p_otro_usuario_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.miembros_organizacion yo
      join public.miembros_organizacion otro
        on otro.organizacion_id = yo.organizacion_id
       and otro.usuario_id = p_otro_usuario_id
       and otro.activo
     where yo.usuario_id = (select auth.uid())
       and yo.activo
  );
$$;

revoke all on function public.es_miembro(uuid) from public;
revoke all on function public.es_admin(uuid) from public;
revoke all on function public.puede_editar(uuid) from public;
revoke all on function public.comparte_organizacion(uuid) from public;
grant execute on function public.es_miembro(uuid) to authenticated;
grant execute on function public.es_admin(uuid) to authenticated;
grant execute on function public.puede_editar(uuid) to authenticated;
grant execute on function public.comparte_organizacion(uuid) to authenticated;

